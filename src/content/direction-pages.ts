/* ───────── Формат полей в админке ─────────
 * Списки — по строке на пункт.
 * Форматы — «Название | Описание | Цена», цена необязательна.
 * Вопросы — блоками через пустую строку: первая строка — вопрос, остальные — ответ.
 */

export function linesToList(value: string): string[] {
  return value
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean);
}

export function formatsToText(formats: DirectionFormat[]): string {
  return formats.map((item) => [item.title, item.text, item.price].filter(Boolean).join(" | ")).join("\n");
}

export function textToFormats(value: string): DirectionFormat[] {
  return linesToList(value)
    .map((line) => {
      const [title = "", text = "", price = ""] = line.split("|").map((part) => part.trim());
      return { title, text, price: price || null };
    })
    .filter((item) => item.title);
}

export function faqToText(faq: DirectionFaq[]): string {
  return faq.map((item) => `${item.q}\n${item.a}`).join("\n\n");
}

export function textToFaq(value: string): DirectionFaq[] {
  return value
    .replace(/\r\n/g, "\n")
    .split(/\n\s*\n/)
    .map((block) => {
      const [q = "", ...rest] = block.trim().split("\n");
      return { q: q.trim(), a: rest.join(" ").trim() };
    })
    .filter((item) => item.q && item.a);
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function stringList(value: unknown): string[] | null {
  if (!Array.isArray(value)) return null;
  const list = value.filter((item): item is string => typeof item === "string" && item.trim() !== "").map((item) => item.trim());
  return list.length > 0 ? list : null;
}

/** Накладывает правки из админки на черновик страницы. Пустые и битые поля игнорируются. */
export function mergeDirectionPage(base: DirectionPage, patch: unknown): DirectionPage {
  if (!isRecord(patch)) return base;
  const page: DirectionPage = { ...base };
  if (typeof patch.lead === "string" && patch.lead.trim()) page.lead = patch.lead.trim();
  page.included = stringList(patch.included) ?? base.included;
  page.steps = stringList(patch.steps) ?? base.steps;
  if (Array.isArray(patch.formats)) {
    const formats = patch.formats
      .filter(isRecord)
      .map((item) => ({
        title: typeof item.title === "string" ? item.title.trim() : "",
        text: typeof item.text === "string" ? item.text.trim() : "",
        price: typeof item.price === "string" && item.price.trim() ? item.price.trim() : null,
      }))
      .filter((item) => item.title);
    if (formats.length > 0) page.formats = formats;
  }
  if (Array.isArray(patch.faq)) {
    const faq = patch.faq
      .filter(isRecord)
      .map((item) => ({ q: typeof item.q === "string" ? item.q.trim() : "", a: typeof item.a === "string" ? item.a.trim() : "" }))
      .filter((item) => item.q && item.a);
    if (faq.length > 0) page.faq = faq;
  }
  return page;
}
